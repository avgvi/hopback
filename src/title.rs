//! Readable session titles.
//!
//! Adapters hand over the best title their agent stores, which is often just
//! the first prompt. First prompts are full of machinery: paste wrappers,
//! slash-command envelopes, injected context blocks, image labels. This module
//! strips that and falls back to the first line a person would recognise.

use crate::model::{truncate_title, Session, ASSISTANT_PREFIX, USER_PREFIX};

/// Longest title stored in the index, in characters.
pub const TITLE_MAX: usize = 80;

/// Shown when a session has no usable text at all.
pub const UNTITLED: &str = "(untitled)";

/// Wrappers whose content is what the user meant: drop the tags, keep the text.
const KEEP_INNER: &[&str] = &[
    "pasted_content",
    "pasted-content",
    "command-args",
    "bash-input",
    "user_query",
    "user-query",
    "user_message",
    "user_input",
    "scheduled-task",
];

/// Blocks added by the agent or its harness: drop the tags and the content.
const DROP_BLOCK: &[&str] = &[
    "system-reminder",
    "system_reminder",
    "environment_context",
    "environment_details",
    "command-message",
    "local-command-stdout",
    "local-command-stderr",
    "local-command-caveat",
    "bash-stdout",
    "bash-stderr",
    "user_instructions",
    "user-prompt-submit-hook",
    "turn_aborted",
    "subagent_notification",
    "task-notification",
    "in-app-browser-context",
    "ide_selection",
    "ide_opened_file",
    "ide_diagnostics",
    "permissions",
    "image",
    "attachments",
    "context",
];

struct Tag<'a> {
    name: &'a str,
    closing: bool,
    /// Byte offset just past the tag's `>`.
    end: usize,
}

/// Parses an XML-ish tag at the very start of `text`: `<name attrs>` or
/// `</name attrs>`. Names are letters, digits, `-`, `_` and `:`, starting with
/// a letter, so comparisons like `<3` or `< 10` are not tags.
fn leading_tag(text: &str) -> Option<Tag<'_>> {
    let rest = text.strip_prefix('<')?;
    let (closing, rest) = match rest.strip_prefix('/') {
        Some(r) => (true, r),
        None => (false, rest),
    };
    let name_len = rest
        .char_indices()
        .find(|(_, c)| !(c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | ':')))
        .map(|(i, _)| i)
        .unwrap_or(rest.len());
    let name = &rest[..name_len];
    if !name.starts_with(|c: char| c.is_ascii_alphabetic()) {
        return None;
    }
    let after_name = &rest[name_len..];
    if !after_name.is_empty()
        && !after_name.starts_with(|c: char| c == '>' || c == '/' || c.is_whitespace())
    {
        return None;
    }
    let close = text.find('>')?;
    // A tag does not span paragraphs; `<foo` followed by prose is not one.
    if text[..close].contains("\n\n") {
        return None;
    }
    Some(Tag {
        name,
        closing,
        end: close + 1,
    })
}

/// Finds `</name` after `from`, returning (start of the closing tag, offset
/// just past its `>`).
fn find_closing(text: &str, name: &str, from: usize) -> Option<(usize, usize)> {
    let needle = format!("</{name}");
    let mut search = from;
    while let Some(pos) = text[search..].find(&needle) {
        let start = search + pos;
        let after = &text[start + needle.len()..];
        if after.is_empty() || after.starts_with(|c: char| c == '>' || c.is_whitespace()) {
            let end = text[start..].find('>').map(|i| start + i + 1)?;
            return Some((start, end));
        }
        search = start + needle.len();
    }
    None
}

fn in_list(list: &[&str], name: &str) -> bool {
    list.iter().any(|n| n.eq_ignore_ascii_case(name))
}

/// What is left of a prompt once the machinery at its front is removed.
struct Stripped {
    text: String,
    /// The command's name, when the prompt was a slash-command envelope.
    command: Option<String>,
    /// Content of the first unknown block that was skipped in favour of the
    /// text after it. Used when nothing else in the prompt is readable, as in
    /// prompts generated by another program that are blocks from end to end.
    skipped: Option<String>,
}

/// Removes machinery from the front of a prompt.
fn strip_wrappers(text: &str) -> Stripped {
    let mut text = text.to_string();
    let mut command = None;
    let mut skipped: Option<String> = None;

    // Each pass removes at least one tag, so the bound is only a guard.
    for _ in 0..64 {
        let trimmed = text.trim_start();
        let Some(tag) = leading_tag(trimmed) else {
            break;
        };
        let after_open = &trimmed[tag.end..];
        if tag.closing {
            text = after_open.to_string();
            continue;
        }

        let Some((close_start, close_end)) = find_closing(trimmed, tag.name, tag.end) else {
            // Unclosed: a standalone label (`<image name=[Image #1]>`) or a
            // wrapper cut off by truncation. Drop the tag itself; for a known
            // noise block with no end in sight there is nothing left to show.
            text = if in_list(DROP_BLOCK, tag.name) && !tag.name.eq_ignore_ascii_case("image") {
                String::new()
            } else {
                after_open.to_string()
            };
            continue;
        };
        let inner = &trimmed[tag.end..close_start];
        let after = &trimmed[close_end..];

        text = if tag.name.eq_ignore_ascii_case("command-name") {
            let name = inner.trim();
            if !name.is_empty() {
                command = Some(name.to_string());
            }
            after.to_string()
        } else if in_list(KEEP_INNER, tag.name) {
            format!("{inner}\n{after}")
        } else if in_list(DROP_BLOCK, tag.name) {
            after.to_string()
        } else if after.trim().is_empty() {
            // An unknown tag around the whole prompt: the content is the prompt.
            inner.to_string()
        } else {
            // An unknown block followed by more text: the text is the prompt.
            if skipped.is_none() && !inner.trim().is_empty() {
                skipped = Some(inner.to_string());
            }
            after.to_string()
        };
    }
    Stripped {
        text,
        command,
        skipped,
    }
}

/// A slash command typed on its own (`/clear`, `/model`), which says nothing
/// about what the session is for.
fn is_bare_slash_command(line: &str) -> bool {
    let Some(rest) = line.strip_prefix('/') else {
        return false;
    };
    !rest.is_empty()
        && rest
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | ':' | '.'))
}

/// Drops a slash command from the front of a line when real text follows it:
/// `/plan tidy the parser` becomes `tidy the parser`. A path such as
/// `/etc/hosts is wrong` is not a command and is left alone.
fn strip_leading_command(line: &str) -> &str {
    let Some((first, rest)) = line.split_once(char::is_whitespace) else {
        return line;
    };
    if is_bare_slash_command(first) && is_meaningful(rest) {
        rest.trim_start()
    } else {
        line
    }
}

/// Trims list, quote and heading markers and image placeholders off one line.
fn tidy_line(line: &str) -> &str {
    let mut line = line.trim();
    loop {
        let before = line;
        line = line
            .trim_start_matches(['#', '>', '*', '-', '=', '`'])
            .trim_start();
        if let Some(rest) = line.strip_prefix("[Image #") {
            if let Some(end) = rest.find(']') {
                line = rest[end + 1..].trim_start();
            }
        }
        if line == before {
            break;
        }
    }
    line
}

fn is_meaningful(line: &str) -> bool {
    line.chars().any(|c| c.is_alphanumeric())
}

/// What `clean` found in one piece of text.
struct Cleaned {
    /// The first line worth showing, or empty.
    line: String,
    /// A slash command seen along the way, as a last-resort title.
    command: Option<String>,
}

fn clean(text: &str) -> Cleaned {
    clean_at_depth(text, 0)
}

fn clean_at_depth(text: &str, depth: u8) -> Cleaned {
    let Stripped {
        text: stripped,
        mut command,
        skipped,
    } = strip_wrappers(text);
    for raw in stripped.lines() {
        let line = tidy_line(raw);
        if !is_meaningful(line) {
            continue;
        }
        if is_bare_slash_command(line) {
            command.get_or_insert_with(|| line.to_string());
            continue;
        }
        // Wrappers can also open mid-prompt, after a line of plain text was
        // skipped; give a line that starts with a tag one more pass.
        if depth < 4 && line.starts_with('<') && leading_tag(line).is_some() {
            let nested = clean_at_depth(line, depth + 1);
            if !nested.line.is_empty() {
                return Cleaned {
                    line: nested.line,
                    command,
                };
            }
            command = command.or(nested.command);
            continue;
        }
        let line = strip_leading_command(line);
        return Cleaned {
            line: line.split_whitespace().collect::<Vec<_>>().join(" "),
            command,
        };
    }
    if depth < 4 {
        if let Some(inner) = skipped {
            let nested = clean_at_depth(&inner, depth + 1);
            return Cleaned {
                line: nested.line,
                command: command.or(nested.command),
            };
        }
    }
    Cleaned {
        line: String::new(),
        command,
    }
}

/// The first meaningful line of `text` with wrappers, command envelopes and
/// markup removed and whitespace collapsed. Empty when nothing is left.
pub fn clean_title(text: &str) -> String {
    clean(text).line
}

/// The user's messages in an indexed `content` string, oldest first.
///
/// Content is messages joined by blank lines, each starting with the user or
/// assistant prefix. A paragraph with neither prefix continues the message
/// before it.
fn user_messages(content: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let mut in_user = false;
    for block in content.split("\n\n") {
        if let Some(text) = block.strip_prefix(USER_PREFIX) {
            out.push(text.to_string());
            in_user = true;
        } else if block.starts_with(ASSISTANT_PREFIX) {
            in_user = false;
        } else if in_user {
            if let Some(last) = out.last_mut() {
                last.push_str("\n\n");
                last.push_str(block);
            }
        }
    }
    out
}

/// Picks the title to index.
///
/// `candidate` is the adapter's title. A candidate that is already clean (a
/// thread name, an AI title, a plain first prompt) is kept. One that starts
/// with machinery is replaced by the first meaningful line among the user's
/// messages in `content`, which are not truncated the way the candidate is.
pub fn derive_title(candidate: &str, content: &str) -> String {
    let candidate = candidate.trim();
    // The mark a translated fork carries in its agent's title. hopback shows
    // its own fork mark in the list instead.
    let candidate = candidate
        .strip_prefix(crate::bridge::FORK_TITLE_MARK)
        .map_or(candidate, str::trim_start);
    let from_candidate = clean(candidate);
    let candidate_was_clean = !from_candidate.line.is_empty() && !candidate.starts_with('<');
    if candidate_was_clean {
        return truncate_title(&from_candidate.line, TITLE_MAX, true);
    }

    let mut command = from_candidate.command;
    for message in user_messages(content) {
        let cleaned = clean(&message);
        if !cleaned.line.is_empty() {
            return truncate_title(&cleaned.line, TITLE_MAX, true);
        }
        command = command.or(cleaned.command);
    }

    if !from_candidate.line.is_empty() {
        return truncate_title(&from_candidate.line, TITLE_MAX, true);
    }
    match command {
        Some(c) => truncate_title(&c, TITLE_MAX, true),
        None => UNTITLED.to_string(),
    }
}

/// Replaces a freshly parsed session's title with its cleaned form. Called
/// once per session by the indexer, for every adapter.
pub fn finalize(session: &mut Session) {
    session.title = derive_title(&session.title, &session.content);
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::join_content;

    fn content(messages: &[(&str, &str)]) -> String {
        let parts: Vec<String> = messages
            .iter()
            .map(|(prefix, text)| format!("{prefix}{text}"))
            .collect();
        join_content(&parts)
    }

    #[test]
    fn the_mark_of_a_translated_fork_is_left_out_of_the_title() {
        assert_eq!(
            derive_title("[hopback] Fix the login bug", ""),
            "Fix the login bug"
        );
    }

    #[test]
    fn plain_titles_are_kept() {
        assert_eq!(
            clean_title("fix the auth middleware bug"),
            "fix the auth middleware bug"
        );
        assert_eq!(derive_title("Uploader retries", ""), "Uploader retries");
        assert_eq!(
            clean_title("compare a < b and c > d"),
            "compare a < b and c > d"
        );
        assert_eq!(clean_title("is x <3 or more?"), "is x <3 or more?");
    }

    #[test]
    fn pasted_content_wrapper_is_stripped() {
        let raw = "<pasted_content id=\"e239\">\n# Task: relaunch `aiz` as `hopback`\n\n## Context\n- Repo\n</pasted_content id=\"e239\">";
        assert_eq!(clean_title(raw), "Task: relaunch `aiz` as `hopback`");
    }

    #[test]
    fn pasted_content_followed_by_the_real_request() {
        let raw = "<pasted_content id=1>\nerror: cannot find type\n</pasted_content>\nwhy does this fail?";
        assert_eq!(clean_title(raw), "error: cannot find type");
    }

    #[test]
    fn truncated_wrapper_without_a_closing_tag() {
        let raw = "<pasted_content id=\"e239\">\n# Task: relaunch aiz as hopback (short comm...";
        assert_eq!(
            clean_title(raw),
            "Task: relaunch aiz as hopback (short comm..."
        );
    }

    #[test]
    fn slash_command_envelope_uses_its_arguments() {
        let raw = "<command-message>review is running…</command-message>\n<command-name>/review</command-name>\n<command-args>the retry patch</command-args>";
        assert_eq!(clean_title(raw), "the retry patch");
    }

    #[test]
    fn slash_command_without_arguments_falls_back_to_the_next_prompt() {
        let envelope = "<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>";
        assert_eq!(clean_title(envelope), "");
        let c = content(&[
            (USER_PREFIX, envelope),
            (USER_PREFIX, "<local-command-stdout></local-command-stdout>"),
            (USER_PREFIX, "add a changelog entry"),
            (ASSISTANT_PREFIX, "Done."),
        ]);
        assert_eq!(derive_title(envelope, &c), "add a changelog entry");
    }

    #[test]
    fn a_session_that_is_only_a_command_is_titled_by_the_command() {
        let envelope = "<command-name>/init</command-name><command-message>init</command-message>";
        let c = content(&[
            (USER_PREFIX, envelope),
            (ASSISTANT_PREFIX, "Created CLAUDE.md"),
        ]);
        assert_eq!(derive_title(envelope, &c), "/init");
        assert_eq!(
            derive_title("/clear", &content(&[(USER_PREFIX, "/clear")])),
            "/clear"
        );
    }

    #[test]
    fn leading_slash_command_is_dropped_when_text_follows() {
        assert_eq!(
            clean_title("/plan tidy the session parser"),
            "tidy the session parser"
        );
        assert_eq!(
            clean_title("/loop 5m check the deploy"),
            "5m check the deploy"
        );
        // Paths and lone slashes are not commands.
        assert_eq!(clean_title("/etc/hosts is wrong"), "/etc/hosts is wrong");
        assert_eq!(clean_title("/ what does this do"), "/ what does this do");
        assert_eq!(
            derive_title("/plan tidy the session parser", ""),
            "tidy the session parser"
        );
        let c = content(&[(USER_PREFIX, "/model"), (USER_PREFIX, "now fix the build")]);
        assert_eq!(derive_title("/model", &c), "now fix the build");
    }

    #[test]
    fn injected_blocks_are_dropped() {
        let raw = "<system-reminder>\nToday's date is 2026-11-11.\n</system-reminder>\nrename the config loader";
        assert_eq!(clean_title(raw), "rename the config loader");

        let only = "<system-reminder>context only</system-reminder>";
        assert_eq!(clean_title(only), "");

        let env = "<environment_context>\n  <cwd>/work</cwd>\n</environment_context>";
        assert_eq!(clean_title(env), "");
    }

    #[test]
    fn image_labels_are_skipped() {
        assert_eq!(clean_title("<image name=[Image #1]>"), "");
        assert_eq!(clean_title("</image>"), "");
        assert_eq!(
            clean_title(
                "<image name=[Image #1]>\n</image>\n[Image #1] what is wrong in this screenshot"
            ),
            "what is wrong in this screenshot"
        );
        let c = content(&[
            (USER_PREFIX, "<image name=[Image #1]>"),
            (USER_PREFIX, "</image>"),
            (USER_PREFIX, "describe this chart"),
            (ASSISTANT_PREFIX, "It shows revenue."),
        ]);
        assert_eq!(
            derive_title("<image name=[Image #1]>", &c),
            "describe this chart"
        );
    }

    #[test]
    fn unknown_block_before_text_is_dropped_and_unknown_wrapper_is_unwrapped() {
        assert_eq!(
            clean_title("<notes_from_app>\nrow 1\nrow 2\n</notes_from_app>\nsummarise my week"),
            "summarise my week"
        );
        assert_eq!(
            clean_title("<request priority=\"high\">\nsummarise my week\n</request>"),
            "summarise my week"
        );
    }

    #[test]
    fn a_prompt_made_only_of_blocks_uses_the_first_readable_block() {
        let raw = "<previous_cards>\n- stand-up notes\n- lunch\n</previous_cards>\n<observations>\n<name>focus</name>\n</observations>\n<system-reminder>ignore</system-reminder>";
        assert_eq!(clean_title(raw), "stand-up notes");
    }

    #[test]
    fn nested_wrappers_unwrap_in_turn() {
        let raw = "<system-reminder>x</system-reminder>\n<pasted_content id=2>\n<command-args>ship it</command-args>\n</pasted_content>";
        assert_eq!(clean_title(raw), "ship it");
    }

    #[test]
    fn markdown_markers_and_whitespace_are_tidied() {
        assert_eq!(
            clean_title("\n\n   ## Plan   for\tthe  week \n more"),
            "Plan for the week"
        );
        assert_eq!(clean_title("> quoted question?"), "quoted question?");
        assert_eq!(clean_title("- [ ] first item"), "[ ] first item");
        assert_eq!(clean_title("---\n\nreal text"), "real text");
        assert_eq!(clean_title("```\ncode line\n```"), "code line");
    }

    #[test]
    fn long_titles_are_truncated_on_a_word() {
        let long = "word ".repeat(40);
        let t = derive_title(&long, "");
        assert!(t.chars().count() <= TITLE_MAX);
        assert!(t.ends_with("..."));
        assert!(!t.contains("  "));
    }

    #[test]
    fn candidate_cut_off_by_the_adapter_is_replaced_from_the_content() {
        // The adapter truncated the wrapper before the prompt even started.
        let candidate = "<pasted_content id=\"a-very-long-identifier-that-eats-the-whole-budget-000000000000\">...";
        let full = "<pasted_content id=\"a-very-long-identifier-that-eats-the-whole-budget-000000000000\">\nmigrate the store to the new schema\n</pasted_content>";
        let c = content(&[(USER_PREFIX, full), (ASSISTANT_PREFIX, "ok")]);
        assert_eq!(
            derive_title(candidate, &c),
            "migrate the store to the new schema"
        );
    }

    #[test]
    fn multi_paragraph_user_messages_stay_one_message() {
        let c = content(&[
            (
                USER_PREFIX,
                "<system-reminder>a\n\nb</system-reminder>\n\nthe actual question",
            ),
            (ASSISTANT_PREFIX, "an answer\n\nwith two paragraphs"),
        ]);
        assert_eq!(
            derive_title("<system-reminder>a", &c),
            "the actual question"
        );
    }

    #[test]
    fn assistant_text_is_never_used_as_a_title() {
        let c = content(&[
            (USER_PREFIX, "<environment_context>x</environment_context>"),
            (ASSISTANT_PREFIX, "Hello, how can I help?"),
        ]);
        assert_eq!(derive_title("<environment_context>x", &c), UNTITLED);
    }

    #[test]
    fn empty_everything_is_untitled() {
        assert_eq!(derive_title("", ""), UNTITLED);
        assert_eq!(derive_title("   \n ", ""), UNTITLED);
    }

    #[test]
    fn finalize_rewrites_the_session_title() {
        let mut s = Session {
            id: "x".into(),
            agent: crate::config::AgentId::Claude,
            title: "<pasted_content id=1>".into(),
            directory: "/w".into(),
            timestamp: 0,
            content: content(&[(
                USER_PREFIX,
                "<pasted_content id=1>\nport the parser\n</pasted_content>",
            )]),
            message_count: 1,
            mtime: 0,
            yolo: false,
            source_path: None,
        };
        finalize(&mut s);
        assert_eq!(s.title, "port the parser");
    }
}
